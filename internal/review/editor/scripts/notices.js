// Writes ../assets/editor-notices.md: license texts for every package bundled
// into ../assets/editor.js, grouped by identical text. Run with Bun after
// `bun run build`: `bun scripts/notices.js`.
import { mkdtempSync, readFileSync, readdirSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const work = mkdtempSync(join(tmpdir(), 'editor-notices-'));
const meta = join(work, 'meta.json');
const result = Bun.spawnSync(['bun', 'build', 'src/main.js', '--outfile', join(work, 'out.js'), '--format', 'iife', '--target', 'browser', '--metafile=' + meta]);
if (result.exitCode !== 0) throw new Error(result.stderr.toString());
const packages = new Set();
for (const input of Object.keys(JSON.parse(readFileSync(meta, 'utf8')).inputs)) {
  const match = input.match(/node_modules\/((?:@[^/]+\/)?[^/]+)\//);
  if (match) packages.add(match[1]);
}
rmSync(work, { recursive: true, force: true });

const groups = new Map();
for (const name of [...packages].sort()) {
  const dir = join('node_modules', name);
  const manifest = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
  const file = readdirSync(dir).find((f) => /^licen[cs]e(\.md|\.txt)?$/i.test(f));
  if (!file) throw new Error('no license file for ' + name);
  const text = readFileSync(join(dir, file), 'utf8').trim();
  const key = manifest.license + '\n' + text;
  if (!groups.has(key)) groups.set(key, { license: manifest.license, text, names: [] });
  groups.get(key).names.push(`${name} ${manifest.version}`);
}

let out = '# Review editor bundle notices\n\nGenerated by internal/review/editor/scripts/notices.js for the packages bundled into editor.js. Versions are pinned in internal/review/editor/package.json and bun.lock.\n';
for (const group of groups.values()) {
  out += `\n## ${group.names.join(', ')}\n\nLicense: ${group.license}\n\n\`\`\`text\n${group.text}\n\`\`\`\n`;
}
writeFileSync('../assets/editor-notices.md', out);
console.log(`${packages.size} packages, ${groups.size} license texts`);
